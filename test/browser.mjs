  assert.match(await fs.readFile(path.join(tmp, 'sequence.puml'), 'utf8'), /@startuml/);
  const htmlDownload = page.waitForEvent('download'); await page.locator('#export-html').click();
  const artifact = await htmlDownload; const artifactPath = path.join(tmp, 'exported.html'); await artifact.saveAs(artifactPath);
  const offline = await context.newPage(); offline.on('pageerror', error => errors.push(error.message));
  await context.setOffline(true); await offline.goto(pathToFileURL(artifactPath).href);
